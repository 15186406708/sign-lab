#!/usr/bin/env python3
"""sign-lab 服务端机密与靶场参数。

这个文件里放的是「服务端才知道的东西」。客户端（被分析方）只能拿到
server/signer.obf.js —— 盐被编码进那张字符串表里，需要静态还原才能拿到。

如果你想把这个靶场当成真实目标来练：把本文件当成看不见的黑盒。
"""

# --- 签名盐 ---------------------------------------------------------------
# 最终签名里拼进去的那个固定串。客户端 JS 里它是从字符串表按索引取出来的。
SERVER_SALT = "s1gnlab7"

# 盐的每个字符在字符串表中的下标（顺序即盐的字符顺序）
SALT_INDEX = (8, 28, 20, 42, 21, 53, 65, 6)

# 生成字符串表用的参数：长度与随机种子。
# 种子固定 → 每次生成的 signer.obf.js 完全一致，靶场可复现。
JS_TABLE_LEN = 80
JS_TABLE_SEED = 20261010

# 字符串表在 JS 里不是明文，每个字符都跟这个掩码异或后以数字形式存在，
# 运行期再用 String.fromCharCode(code ^ mask) 还原。
JS_TABLE_MASK = 0x3C

# --- 校验参数 -------------------------------------------------------------
NONCE_TTL_SEC = 300          # nonce 只能用一次，缓存 5 分钟
TS_SKEW_MS = 300_000         # 客户端时间戳与服务端相差不得超过 ±5 分钟
MAX_SIZE = 50                # 服务端 page_size 硬上限（超过就截断到 50）
TOTAL_ITEMS = 137            # 合成数据集的总条数

# --- 限流参数（令牌桶，按客户端 IP 计）-------------------------------------
# 容量 3：连发 3 次后会开始被拦；之后每 2 秒恢复 1 个令牌。
RATE_CAPACITY = 3
RATE_REFILL_PER_SEC = 0.5
